#!/usr/bin/env python3
"""Stamp a static release. No dependencies, minifier, credential or deletion."""
from pathlib import Path
import hashlib, json, re
ROOT = Path(__file__).resolve().parents[1]
html = (ROOT/'index.html').read_text()
html = re.sub(r'\?v=[0-9a-f]+', '', html)
html = re.sub(r'<meta name="mobile-build" content="[^"]+">\n?', '', html)
files = sorted([*ROOT.glob('js/**/*.js'), *ROOT.glob('css/*.css'), *[p for p in ROOT.glob('assets/**/*') if p.is_file()], ROOT/'manifest.webmanifest', Path(__file__).resolve()])
h = hashlib.sha256(html.encode())
for p in files:
    h.update(str(p.relative_to(ROOT)).encode()); h.update(p.read_bytes())
v = h.hexdigest()[:16]
html = html.replace('<meta charset="utf-8">', f'<meta charset="utf-8">\n<meta name="mobile-build" content="{v}">')
html = re.sub(r'((?:src|href)="(?:js|css)/[^"?]+\.(?:js|css))"', rf'\1?v={v}"', html)
(ROOT/'index.html').write_text(html)
(ROOT/'version.json').write_text(json.dumps({'v': v})+'\n')
precache = ['./','./index.html','./manifest.webmanifest','./favicon.ico']
precache += re.findall(r'(?:src|href)="((?:js|css)/[^" ]+)"',html)
precache += ['assets/fonts/PixelifyPS-400.ttf','assets/fonts/PixelifyPS-700.ttf']
precache += ['assets/icons/icon-180.png','assets/icons/icon-192.png','assets/icons/icon-512.png','assets/icons/icon-maskable-512.png']
sw = '''// Generated by tools/build.py. Cache scope is isolated to this GitHub Pages path.
const VERSION = __VERSION__;
const PREFIX = 'pokesurvivor-mobile:' + new URL(self.registration.scope).pathname + ':';
const CODE = PREFIX + VERSION, ASSETS = PREFIX + 'assets:' + VERSION;
const CORE = __CORE__;
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CODE).then(cache => cache.addAll(CORE.map(path => new Request(path, {cache:'reload'})))));
  // Do not force a replacement while another window is playing.
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith(PREFIX) && key !== CODE && key !== ASSETS) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const req = event.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;
  if (url.pathname.endsWith('/version.json') || url.pathname.endsWith('/sw.js')) return;
  event.respondWith((async () => {
    const code = await caches.open(CODE);
    if (req.mode === 'navigate') {
      try {
        const response = await fetch(req, {cache:'no-cache'});
        if (!response.ok) throw new Error('Offline');
        // Keep this release's precached HTML intact for a consistent offline fallback.
        return response;
      } catch { return (await code.match('./index.html')) || Response.error(); }
    }
    const hit = await code.match(req);
    if (hit) return hit; // JS/CSS URLs carry the release hash.
    if (url.pathname.includes('/assets/')) {
      const assets = await caches.open(ASSETS);
      const cached = await assets.match(req);
      if (cached) return cached;
      const response = await fetch(req);
      if (response.ok) event.waitUntil(assets.put(req,response.clone()).catch(() => {}));
      return response;
    }
    return fetch(req); // Never serve unrelated/old JS for a missing versioned URL.
  })());
});
'''.replace('__VERSION__',json.dumps(v)).replace('__CORE__',json.dumps(precache))
(ROOT/'sw.js').write_text(sw)
print('Built release',v,'with',len(precache),'core cache entries')
